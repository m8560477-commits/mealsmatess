import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { generateAndSaveAiImage } from "@/lib/recipe-images.server";

const mocks = vi.hoisted(() => ({
  put: vi.fn(),
  del: vi.fn(),
  generate: vi.fn(),
  update: vi.fn(),
  eq: vi.fn(),
}));
vi.mock("@vercel/blob", () => ({ put: mocks.put, del: mocks.del }));
vi.mock("@/lib/ai-engine.server", () => ({
  generateAiImage: mocks.generate,
  generateAiObject: vi.fn(),
}));
vi.mock("@/server/firebase-admin", () => ({
  firebaseAdmin: { from: () => ({ update: mocks.update }) },
}));

const url =
  "https://synthetic.public.blob.vercel-storage.com/recipe-images/recipe-1/photo-unique.png";
const recipe = { id: "recipe-1", name: "Tomato soup", ingredients: ["tomato"], steps: ["Simmer"] };
const bytes = new Uint8Array([137, 80, 78, 71]);

describe("generated recipe photos in Vercel Blob", () => {
  beforeEach(() => {
    vi.resetAllMocks();
    vi.stubEnv("BLOB_READ_WRITE_TOKEN", "synthetic-test-token");
    vi.stubEnv("BLOB_STORE_ID", "");
    mocks.generate.mockResolvedValue({ bytes, mediaType: "image/png", model: "test-model" });
    mocks.put.mockResolvedValue({ url });
    mocks.del.mockResolvedValue(undefined);
    mocks.update.mockReturnValue({ eq: mocks.eq });
    mocks.eq.mockResolvedValue({ error: null });
  });
  afterEach(() => vi.unstubAllEnvs());

  it("persists the public Blob URL after uploading the generated bytes", async () => {
    expect(await generateAndSaveAiImage(recipe, "signature")).toBe(url);
    expect(mocks.put).toHaveBeenCalledWith(
      "recipe-images/recipe-1/signature.png",
      Buffer.from(bytes),
      expect.objectContaining({
        access: "public",
        contentType: "image/png",
        addRandomSuffix: true,
        allowOverwrite: false,
      }),
    );
    expect(mocks.update).toHaveBeenCalledWith(
      expect.objectContaining({
        image_url: url,
        image_source: "AI",
        image_signature: "signature",
        image_attribution: { generated: true, model: "test-model" },
      }),
    );
    expect(mocks.eq).toHaveBeenCalledWith("id", "recipe-1");
    expect(mocks.del).not.toHaveBeenCalled();
  });

  it("accepts a connected store using Vercel OIDC without a static token", async () => {
    vi.stubEnv("BLOB_READ_WRITE_TOKEN", "");
    vi.stubEnv("BLOB_STORE_ID", "store_synthetic");
    await expect(generateAndSaveAiImage(recipe, "signature")).resolves.toBe(url);
  });

  it("fails before spending on generation when no Blob store is configured", async () => {
    vi.stubEnv("BLOB_READ_WRITE_TOKEN", "");
    await expect(generateAndSaveAiImage(recipe, "signature")).rejects.toThrow(
      /Connect a public Vercel Blob store/,
    );
    expect(mocks.generate).not.toHaveBeenCalled();
    expect(mocks.put).not.toHaveBeenCalled();
  });

  it("does not save a recipe URL when the upload fails", async () => {
    mocks.put.mockRejectedValue(new Error("Blob store unavailable"));
    await expect(generateAndSaveAiImage(recipe, "signature")).rejects.toThrow(
      "Blob store unavailable",
    );
    expect(mocks.update).not.toHaveBeenCalled();
    expect(mocks.del).not.toHaveBeenCalled();
  });

  it("removes the new upload if saving the recipe fails", async () => {
    mocks.eq.mockResolvedValue({ error: new Error("Database write failed") });
    await expect(generateAndSaveAiImage(recipe, "signature")).rejects.toThrow(
      "Database write failed",
    );
    expect(mocks.del).toHaveBeenCalledWith(url);
  });

  it("rejects an oversized model image before upload or database writes", async () => {
    mocks.generate.mockResolvedValue({
      bytes: new Uint8Array(20 * 1024 * 1024 + 1),
      mediaType: "image/png",
    });
    await expect(generateAndSaveAiImage(recipe, "signature")).rejects.toThrow(/storage size limit/);
    expect(mocks.put).not.toHaveBeenCalled();
    expect(mocks.update).not.toHaveBeenCalled();
  });
});
